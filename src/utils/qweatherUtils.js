/**
 * 统一地名翻译：城市 → 省州 → 国家 逐级回退
 * 对带行政区后缀的名称（如 "Province of X"）做清洗后再查
 */
export function translateGeoName(name) {
  if (!name) return ''
  const raw = String(name).trim()
  if (!raw) return ''

  // 精确匹配
  if (CITY_ZH[raw]) return CITY_ZH[raw]
  if (ADMIN1_ZH[raw]) return ADMIN1_ZH[raw]
  if (COUNTRY_ZH[raw]) return COUNTRY_ZH[raw]

  // 兜底：去掉常见行政区后缀后再查
  const sanitized = raw
    .replace(/^(Province|State|Region|City|District|Prefecture|Governorate|Wilaya)\s+(of\s+)?/i, '')
    .replace(/\s+(Province|State|Region|City|District|Prefecture|Governorate|Wilaya)$/i, '')
    .trim()

  if (sanitized && sanitized !== raw) {
    if (CITY_ZH[sanitized]) return CITY_ZH[sanitized]
    if (ADMIN1_ZH[sanitized]) return ADMIN1_ZH[sanitized]
    if (COUNTRY_ZH[sanitized]) return COUNTRY_ZH[sanitized]
  }

  return raw
}

/** 拼接「原名 + (中文翻译)」用于 UI 展示，确保所有条目都带中文翻译 */
export function formatGeoWithZh(name) {
  if (!name) return ''
  const raw = String(name).trim()
  const zh = translateGeoName(raw)
  if (!zh) return raw
  return `${raw} (${zh})`
}