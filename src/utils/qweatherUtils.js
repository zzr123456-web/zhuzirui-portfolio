export function getIconInfo(code) {
  const key = String(code).padStart(3, '0')
  return ICON_MAP[key] ?? { desc: '未知', icon: '❓', theme: 'cloud' }
}

export function getThemeGradient(code) {
  const { theme } = getIconInfo(code)
  return THEME_GRADIENTS[theme] ?? THEME_GRADIENTS.cloud
}

export function formatDate(fxDate) {
  if (!fxDate) return { date: '--/--', weekday: '--' }
  const [y, m, d] = fxDate.split('-').map(Number)
  const date = new Date(y, m - 1, d)
  const mm = String(m).padStart(2, '0')
  const dd = String(d).padStart(2, '0')
  const weekdays = ['周日', '周一', '周二', '周三', '周四', '周五', '周六']
  return {
    date: `${mm}-${dd}`,
    weekday: weekdays[date.getDay()],
  }
}

export function uvCategory(level) {
  const n = Number(level)
  if (Number.isNaN(n)) return '无数据'
  if (n <= 2) return '弱'
  if (n <= 5) return '中'
  if (n <= 7) return '强'
  if (n <= 10) return '很强'
  return '极强'
}

